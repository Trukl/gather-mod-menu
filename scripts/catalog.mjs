import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { catalogErrors } from "../launcher/mod-release.mjs";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const BUNDLE_PATH = join(ROOT, "gather-mod-menu.js");
export const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");

const META_FIELDS = [
  "id",
  "kind",
  "name",
  "description",
  "icon",
  "version",
  "requires",
  "changelog",
];
export const moduleMeta = (m) => Object.fromEntries(META_FIELDS.map((k) => [k, m[k]]));

export function loadLocalCatalog() {
  const { modules } = JSON.parse(readFileSync(join(ROOT, "modules.json"), "utf8"));
  const errors = catalogErrors(modules);
  if (errors.length) throw new Error("Invalid modules.json:\n- " + errors.join("\n- "));
  return modules.map((m) => {
    const code = readFileSync(join(ROOT, m.file), "utf8");
    return { ...moduleMeta(m), hash: sha256(code), code };
  });
}

export function buildBundle(modules) {
  const [core, ...rest] = modules;
  const catalog = { modules: modules.map(moduleMeta) };
  return [
    "// Gather Mods — every module in one file, for pasting into the DevTools console",
    "// of an app.v2.gather.town tab. Generated by `npm run bundle` from src/; do not edit.",
    "// Pick the modules to run in ⚙ Settings. No automatic updates in this mode.",
    core.code,
    `window.__gatherMods.bundleCatalog = ${JSON.stringify(catalog)};`,
    ...rest.map((m) => m.code),
  ].join("\n");
}
